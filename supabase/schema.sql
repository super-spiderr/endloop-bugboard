-- Endloop test board: database schema for Supabase.
-- Run this once in the Supabase SQL editor (Project > SQL Editor > New query).
--
-- How access works:
--   * The tables are closed to the public API (RLS on, no policies, privileges revoked).
--   * The page only talks to the database through the functions below.
--   * Every function takes a passcode. The tester code can read the board and add
--     bugs and suggestions. The admin code can do everything.
--   * Codes are stored hashed (bcrypt). Set them with set-codes.sql.

create extension if not exists pgcrypto with schema extensions;

-- Tables -------------------------------------------------------------------

create table if not exists public.board_codes (
  role       text primary key check (role in ('tester', 'admin')),
  code_hash  text not null
);

create table if not exists public.bugs (
  id          uuid primary key default gen_random_uuid(),
  num         integer generated by default as identity unique,
  data        jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.suggestions (
  id          uuid primary key default gen_random_uuid(),
  num         integer generated by default as identity unique,
  data        jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.roasts (
  id          text primary key,
  data        jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now()
);

alter table public.board_codes enable row level security;
alter table public.bugs        enable row level security;
alter table public.suggestions enable row level security;
alter table public.roasts      enable row level security;

revoke all on public.board_codes, public.bugs, public.suggestions, public.roasts
  from anon, authenticated;

-- Helpers ------------------------------------------------------------------

-- Returns 'admin', 'tester' or null for a passcode.
create or replace function public.board_role(p_code text)
returns text
language sql
stable
security definer
set search_path = public, extensions
as $$
  select role
  from public.board_codes
  where code_hash = crypt(coalesce(p_code, ''), code_hash)
  order by case role when 'admin' then 0 else 1 end
  limit 1
$$;

revoke all on function public.board_role(text) from public, anon, authenticated;

-- Raises 'wrong_code' (after a short pause, to slow guessing) or returns the role.
create or replace function public.board_require(p_code text, p_admin boolean)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  r text := public.board_role(p_code);
begin
  if r is null then
    perform pg_sleep(1);
    raise exception 'wrong_code' using errcode = '28000';
  end if;
  if p_admin and r <> 'admin' then
    raise exception 'admin_only' using errcode = '42501';
  end if;
  return r;
end
$$;

revoke all on function public.board_require(text, boolean) from public, anon, authenticated;

create or replace function public.board_item(p_id text, p_num integer, p_data jsonb, p_created timestamptz)
returns jsonb
language sql
immutable
as $$
  select jsonb_build_object('createdAt', p_created) || p_data
         || jsonb_build_object('id', p_id, 'num', p_num)
$$;

-- Read ---------------------------------------------------------------------

create or replace function public.board_read(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  r text := public.board_require(p_code, false);
begin
  return jsonb_build_object(
    'role', r,
    'bugs', coalesce((
      select jsonb_agg(public.board_item(b.id::text, b.num, b.data, b.created_at) order by b.num)
      from public.bugs b), '[]'::jsonb),
    'suggestions', coalesce((
      select jsonb_agg(public.board_item(s.id::text, s.num, s.data, s.created_at) order by s.num)
      from public.suggestions s), '[]'::jsonb),
    'roasts', coalesce((
      select jsonb_agg(r2.data || jsonb_build_object('id', r2.id) order by r2.id)
      from public.roasts r2), '[]'::jsonb)
  );
end
$$;

-- Write --------------------------------------------------------------------

-- Bugs and suggestions share the same rules:
--   p_id null  -> add a new item (tester or admin). Testers' items always start as 'new'.
--   p_id given -> change an existing item (admin only).
create or replace function public.board_save(p_code text, p_kind text, p_id uuid, p_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  r     text := public.board_require(p_code, p_id is not null);
  clean jsonb := coalesce(p_data, '{}'::jsonb) - 'id' - 'num';
  row_id uuid; row_num integer; row_data jsonb; row_created timestamptz;
begin
  if jsonb_typeof(clean) <> 'object' or octet_length(clean::text) > 20000 then
    raise exception 'bad_data' using errcode = '22023';
  end if;
  if r = 'tester' then
    clean := clean || '{"status":"new"}'::jsonb;
  end if;

  if p_kind = 'bug' then
    if p_id is null then
      insert into public.bugs (data) values (clean)
      returning id, num, data, created_at into row_id, row_num, row_data, row_created;
    else
      update public.bugs set data = clean, updated_at = now() where id = p_id
      returning id, num, data, created_at into row_id, row_num, row_data, row_created;
    end if;
  elsif p_kind = 'suggestion' then
    if p_id is null then
      insert into public.suggestions (data) values (clean)
      returning id, num, data, created_at into row_id, row_num, row_data, row_created;
    else
      update public.suggestions set data = clean, updated_at = now() where id = p_id
      returning id, num, data, created_at into row_id, row_num, row_data, row_created;
    end if;
  else
    raise exception 'bad_kind' using errcode = '22023';
  end if;

  if row_id is null then
    raise exception 'not_found' using errcode = 'P0002';
  end if;
  return public.board_item(row_id::text, row_num, row_data, row_created);
end
$$;

-- Roast lines: admin only. Adds the line if the id is new, otherwise replaces it.
create or replace function public.board_save_roast(p_code text, p_id text, p_data jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  clean jsonb := coalesce(p_data, '{}'::jsonb) - 'id';
begin
  perform public.board_require(p_code, true);
  if p_id is null or p_id !~ '^[a-zA-Z0-9_]{1,40}$' then
    raise exception 'bad_id' using errcode = '22023';
  end if;
  if jsonb_typeof(clean) <> 'object' or octet_length(clean::text) > 20000 then
    raise exception 'bad_data' using errcode = '22023';
  end if;
  insert into public.roasts (id, data) values (p_id, clean)
  on conflict (id) do update set data = excluded.data, updated_at = now();
  return clean || jsonb_build_object('id', p_id);
end
$$;

create or replace function public.board_delete(p_code text, p_kind text, p_id text)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  perform public.board_require(p_code, true);
  if p_kind = 'bug' then
    delete from public.bugs where id = p_id::uuid;
  elsif p_kind = 'suggestion' then
    delete from public.suggestions where id = p_id::uuid;
  elsif p_kind = 'roast' then
    delete from public.roasts where id = p_id;
  else
    raise exception 'bad_kind' using errcode = '22023';
  end if;
end
$$;

-- Only these four functions are callable from the page.
revoke all on function public.board_item(text, integer, jsonb, timestamptz) from public, anon, authenticated;
revoke all on function public.board_read(text)                              from public;
revoke all on function public.board_save(text, text, uuid, jsonb)           from public;
revoke all on function public.board_save_roast(text, text, jsonb)           from public;
revoke all on function public.board_delete(text, text, text)                from public;
grant execute on function public.board_read(text)                    to anon, authenticated;
grant execute on function public.board_save(text, text, uuid, jsonb) to anon, authenticated;
grant execute on function public.board_save_roast(text, text, jsonb) to anon, authenticated;
grant execute on function public.board_delete(text, text, text)      to anon, authenticated;
