-- Endloop test board: roast admin (bulk edits, import, published versions for the app).
-- Run once in the Supabase SQL editor, after schema.sql and attachments.sql. Safe to re-run.
--
-- What it adds
--   * board_save_roasts   admin: save many roast rows and delete others in one go (bulk edit, import).
--   * board_publish_roasts admin: store a new published version of the roast packs and make it live.
--   * board_releases      tester or admin: list published versions (no line text).
--   * board_set_live      admin: make an older version live again (rollback) or a newer one.
--   * roast_manifest()    PUBLIC, no passcode: which version is live, with a checksum per language.
--   * roast_pack(lang)    PUBLIC, no passcode: the live pack for one language, for the app to download.
--
-- Only published versions are public. Drafts, review notes and tester names never leave the board.

-- Published versions --------------------------------------------------------

create table if not exists public.roast_releases (
  version     integer generated by default as identity primary key,
  packs       jsonb not null,             -- { "en": {pack doc}, "ta-Latn": {pack doc} }
  counts      jsonb not null default '{}'::jsonb,
  sha256      jsonb not null default '{}'::jsonb,
  notes       text not null default '',
  created_by  text not null default '',
  created_at  timestamptz not null default now()
);

create table if not exists public.roast_live (
  id          integer primary key default 1 check (id = 1),
  version     integer references public.roast_releases (version),
  updated_at  timestamptz not null default now()
);
insert into public.roast_live (id, version) values (1, null) on conflict (id) do nothing;

alter table public.roast_releases enable row level security;
alter table public.roast_live     enable row level security;
revoke all on public.roast_releases, public.roast_live from anon, authenticated;

-- Bulk save -----------------------------------------------------------------

-- p_rows: [{ "id": "en_lh_s03", "data": { ... } }, ...]   (upsert, replaces data)
-- p_delete: ids to delete. Both happen in one transaction.
create or replace function public.board_save_roasts(p_code text, p_rows jsonb, p_delete text[])
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  item jsonb;
  rid  text;
  clean jsonb;
  saved integer := 0;
  removed integer := 0;
begin
  perform public.board_require(p_code, true);
  if p_rows is null then p_rows := '[]'::jsonb; end if;
  if jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) > 3000 or octet_length(p_rows::text) > 4000000 then
    raise exception 'bad_data' using errcode = '22023';
  end if;
  for item in select * from jsonb_array_elements(p_rows) loop
    rid := item->>'id';
    clean := coalesce(item->'data', '{}'::jsonb) - 'id';
    if rid is null or rid !~ '^[a-zA-Z0-9_]{1,60}$' then
      raise exception 'bad_id' using errcode = '22023';
    end if;
    if jsonb_typeof(clean) <> 'object' or octet_length(clean::text) > 20000 then
      raise exception 'bad_data' using errcode = '22023';
    end if;
    insert into public.roasts (id, data) values (rid, clean)
    on conflict (id) do update set data = excluded.data, updated_at = now();
    saved := saved + 1;
  end loop;
  if p_delete is not null and array_length(p_delete, 1) > 0 then
    delete from public.roasts where id = any (p_delete);
    get diagnostics removed = row_count;
  end if;
  return jsonb_build_object('saved', saved, 'deleted', removed);
end
$$;

-- Publish -------------------------------------------------------------------

-- p_packs: { "en": {pack doc with "roasts": [...]}, "ta-Latn": {...} }, built by the board
-- from the live lines. Stored as-is and made live straight away.
create or replace function public.board_publish_roasts(p_code text, p_packs jsonb, p_notes text, p_by text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  lang text;
  pack jsonb;
  counts jsonb := '{}'::jsonb;
  shas jsonb := '{}'::jsonb;
  v integer;
begin
  perform public.board_require(p_code, true);
  if p_packs is null or jsonb_typeof(p_packs) <> 'object' or not (p_packs ? 'en')
     or octet_length(p_packs::text) > 6000000 then
    raise exception 'bad_data' using errcode = '22023';
  end if;
  for lang, pack in select key, value from jsonb_each(p_packs) loop
    if lang !~ '^[a-zA-Z-]{2,12}$' or jsonb_typeof(pack->'roasts') <> 'array' or jsonb_array_length(pack->'roasts') = 0 then
      raise exception 'bad_data' using errcode = '22023';
    end if;
    counts := counts || jsonb_build_object(lang, jsonb_array_length(pack->'roasts'));
    shas := shas || jsonb_build_object(lang, encode(extensions.digest(pack::text, 'sha256'), 'hex'));
  end loop;
  insert into public.roast_releases (packs, counts, sha256, notes, created_by)
  values (p_packs, counts, shas, left(coalesce(p_notes, ''), 500), left(coalesce(p_by, ''), 80))
  returning version into v;
  update public.roast_live set version = v, updated_at = now() where id = 1;
  return jsonb_build_object('version', v, 'counts', counts);
end
$$;

create or replace function public.board_releases(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  perform public.board_require(p_code, false);
  return jsonb_build_object(
    'live', (select version from public.roast_live where id = 1),
    'releases', coalesce((
      select jsonb_agg(jsonb_build_object(
        'version', r.version, 'counts', r.counts, 'notes', r.notes,
        'createdBy', r.created_by, 'createdAt', r.created_at) order by r.version desc)
      from public.roast_releases r), '[]'::jsonb));
end
$$;

-- The full packs of one version (admin), used to compare the board with what's live.
create or replace function public.board_release_packs(p_code text, p_version integer)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  perform public.board_require(p_code, true);
  return (select packs from public.roast_releases where version = p_version);
end
$$;

create or replace function public.board_set_live(p_code text, p_version integer)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  perform public.board_require(p_code, true);
  if not exists (select 1 from public.roast_releases where version = p_version) then
    raise exception 'not_found' using errcode = 'P0002';
  end if;
  update public.roast_live set version = p_version, updated_at = now() where id = 1;
  return jsonb_build_object('live', p_version);
end
$$;

-- Public, for the app -------------------------------------------------------
-- GET {SUPABASE_URL}/rest/v1/rpc/roast_manifest            (headers: apikey)
-- GET {SUPABASE_URL}/rest/v1/rpc/roast_pack?p_lang=ta-Latn  (headers: apikey)

create or replace function public.roast_manifest()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select case when r.version is null then jsonb_build_object('version', 0, 'packs', '[]'::jsonb)
  else jsonb_build_object(
    'version', r.version,
    'publishedAt', r.created_at,
    'packs', (select jsonb_agg(jsonb_build_object('lang', k, 'count', (r.counts->>k)::int, 'sha256', r.sha256->>k))
              from jsonb_object_keys(r.packs) k))
  end
  from public.roast_live l left join public.roast_releases r on r.version = l.version
  where l.id = 1
$$;

create or replace function public.roast_pack(p_lang text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select r.packs->p_lang
  from public.roast_live l join public.roast_releases r on r.version = l.version
  where l.id = 1
$$;

